    ];

    /**
     * @return array<int,string> code → text
     */
    public static function map(string $name): array
    {
        $out = [];
        for ($code = 0x20; $code <= 0xFF; $code++) {
            $cp = match ($name) {
                'WinAnsiEncoding' => WinAnsi::codepoint($code),
                'MacRomanEncoding' => $code < 0x80 ? $code : self::MAC_ROMAN_HIGH[$code - 0x80],
                default => self::STANDARD[$code] ?? ($code < 0x7F ? $code : null),
            };
            if ($cp !== null) {
                $out[$code] = mb_chr($cp, 'UTF-8');
            }
        }

        return $out;
    }
}
